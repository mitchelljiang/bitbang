/** Writes src/topics/ccdata.ts from the real tools (see ccgen.ts). Run with `npm run gen-cc`. */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { generate, haveTools } from './ccgen';

if (!haveTools()) {
  console.error('Needs clang with an Arm target, objdump, and LLD: python3 -m venv .venv && .venv/bin/pip install ziglang');
  process.exit(1);
}
generate().then((data) => {
writeFileSync(resolve('src/topics/ccdata.ts'),
  `// Generated by \`npm run gen-cc\` from scripts/ccgen.ts, with ${data.clang}. Do not edit; verify checks it.\n` +
  `export const CC = ${JSON.stringify(data)};\n`);
console.log(`wrote src/topics/ccdata.ts (${data.clang})`);
});
